import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {decodeCanonical,encodeCanonical} from '@dtr/timeline-runtime/runtime/canonical';
import {sha256} from '@dtr/timeline-runtime/runtime/seal';
import {decodeWorld,encodeWorld,ENTRY_IDENTITY,COMBINED_IDENTITY,DEFLECTOR_IDENTITY} from '../../packages/kernels/b2z/world.mjs';
import {migrateDeflectorWorld} from '../../packages/kernels/b2z/deflectors-v12.mjs';
const [before,after,which,statusPath]=process.argv.slice(2);
const read=(d,f)=>fs.readFile(d+'/'+f);
const p=decodeCanonical(await read(before,'publication.bin'));
const n=decodeCanonical(await read(after,'publication.bin'));
const id=p.head.segment_id;
const raw=await read(before,id+'-state.bin');
const next=await read(after,n.head.segment_id+'-state.bin');
const world=decodeWorld(raw);
const deflect=which==='12';
const expectedId={...(deflect?DEFLECTOR_IDENTITY:COMBINED_IDENTITY),source_id:p.identity.source_id};
assert.deepEqual({...p.identity},{...(deflect?COMBINED_IDENTITY:ENTRY_IDENTITY),source_id:p.identity.source_id});
assert.deepEqual({...n.identity},expectedId);
assert.equal(n.head.seal,null);
assert.equal(n.head.segment_id,p.head.segment_id+1n);
assert.equal(n.head.logical_end,p.head.logical_end);
assert.equal(n.head.source_to_exclusive,p.head.source_to_exclusive);
assert.equal(n.epoch.predecessor.manifest_hash,p.head.manifest_hash);
assert.equal(n.epoch.predecessor.publication_hash,sha256(await read(before,'publication.bin')));
const fence=JSON.parse(await fs.readFile(statusPath,'utf8')).transition;
assert.equal(fence.phase,'ready');
const index=BigInt(fence.index_synced.$integer??fence.index_synced),cutover=BigInt(fence.ledger_cutover.$integer??fence.ledger_cutover);
assert(index>=cutover && cutover>=p.head.source_to_exclusive);
assert.equal(sha256(raw),p.head.state_hash);
assert.equal(sha256(next),n.head.state_hash);
assert.equal(world.time[0],p.head.logical_end);
assert.equal(world.time[1],1n);
const source_anchor=p.head.seal?.source_anchor??p.epoch.source_anchor;
assert.equal(n.epoch.source_anchor,source_anchor);
const expected={version:deflect?8:7,migration:deflect?'B2Z_BOUNDARY_DEFLECTOR_RULES_12':'B2Z_CLEARANCE_WAR_CRY_RULES_11',old_identity:p.identity,new_identity:expectedId,previous_state:sha256(raw),new_state:sha256(next),...deflect?{preserved_predecessor_projection:sha256(raw)}:{},logical_boundary:world.time,source_cursor:p.head.source_to_exclusive,ledger_cutover:cutover,account_history_complete_through:cutover,index_synced:index,source_anchor,memo_adapter_before:deflect?6:4,memo_adapter_after:deflect?7:6};
assert.equal(sha256(encodeCanonical(expected)),n.epoch.metadata_hash);
const version=deflect?7:6;
const audit={version,receipts:[],events:[{kind:deflect?'deflector_rules_activated':'rules_activated',sequence:0,time:world.time,context:expected}]};
assert(Buffer.from(encodeCanonical(audit)).equals(await read(after,n.head.segment_id+'-events.bin')));
assert(Buffer.from(encodeCanonical({version,area_time:[]})).equals(await read(after,n.head.segment_id+'-scores.bin')));
assert(next.equals(deflect?Buffer.from(encodeWorld(migrateDeflectorWorld(world))):raw));
if(deflect){
 const projected=decodeCanonical(next);
 assert.equal(projected.version,7);
 assert.equal(projected.deflectors.length,0);
 assert.equal(projected.next_deflector_id,1);
 for(const ball of projected.balls){assert.equal(ball.den,1n);delete ball.den;}
 delete projected.deflectors;delete projected.next_deflector_id;projected.version=6;
 assert(Buffer.from(encodeCanonical(projected)).equals(raw));
}
console.log(JSON.stringify({status:'PASS',epoch:n.epoch.transition_hash,predecessor:id,successor:n.head.segment_id,metadata_hash:n.epoch.metadata_hash,context:expected,state_equivalence:deflect?'exact schema6 reverse projection':'exact predecessor bytes'},(_key,value)=>typeof value==='bigint'?String(value):value,2));
